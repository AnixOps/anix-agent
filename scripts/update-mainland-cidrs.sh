#!/usr/bin/env bash
# Regenerates core/anixcore/mainland_cidrs.txt, the mainland-China address
# blocks an exit node refuses when Control turns that on (exit_policy),
# from APNIC's public delegation file. Run it before a release and commit
# the result. Needs curl and python3.
set -euo pipefail

source_url="${APNIC_DELEGATED_URL:-https://ftp.apnic.net/stats/apnic/delegated-apnic-latest}"
out="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/core/anixcore/mainland_cidrs.txt"
tmp="$(mktemp)"
trap 'rm -f "$tmp" "$tmp.out"' EXIT

curl -fsSL --retry 3 "$source_url" -o "$tmp"

python3 -I - "$tmp" "$source_url" >"$tmp.out" <<'EOF'
import ipaddress, sys

v4, v6 = [], []
with open(sys.argv[1]) as delegated:
    for line in delegated:
        fields = line.strip().split("|")
        if len(fields) < 7 or fields[1] != "CN" or fields[6] not in ("allocated", "assigned"):
            continue
        if fields[2] == "ipv4":
            first = ipaddress.IPv4Address(fields[3])
            v4 += ipaddress.summarize_address_range(first, first + int(fields[4]) - 1)
        elif fields[2] == "ipv6":
            v6.append(ipaddress.IPv6Network(f"{fields[3]}/{fields[4]}"))
blocks = list(ipaddress.collapse_addresses(v4)) + list(ipaddress.collapse_addresses(v6))
if len(blocks) < 1000:
    sys.exit(f"only {len(blocks)} blocks in {sys.argv[1]}; refusing to write the list")
print(f"# Mainland-China address blocks (APNIC delegations for CN): {len(blocks)} entries.")
print(f"# Generated by scripts/update-mainland-cidrs.sh from {sys.argv[2]}")
for block in blocks:
    print(block)
EOF

mv "$tmp.out" "$out"
echo "wrote $(grep -vc '^#' "$out") blocks to $out"
